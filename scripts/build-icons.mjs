// Regenerates src/icons.js from the Lucide icon set (ISC licence).
// Run after changing the list below:  node scripts/build-icons.mjs
// The output is committed, so a normal install does not need the Lucide package.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'node_modules', '@lucide', 'icons', 'dist', 'esm', 'icons');

const NAMES = [
  'anvil', 'axe', 'backpack', 'beer', 'bell-ring', 'book-open', 'book-user', 'castle', 'check', 'chevron-down',
  'chevron-left', 'chevron-right', 'chevron-up', 'chevrons-left', 'chevrons-right', 'circle', 'circle-alert',
  'circle-check', 'circle-dashed', 'circle-user', 'cloud-fog', 'compass', 'copy', 'crosshair', 'crown', 'dices',
  'diamond', 'door-open', 'download', 'drama', 'droplet', 'ellipsis', 'eraser', 'expand', 'external-link', 'eye',
  'eye-off', 'feather', 'file-text', 'flag', 'flame', 'ghost', 'gem', 'grid-3x3', 'hand', 'headphones', 'heart-pulse',
  'hexagon', 'hourglass', 'image', 'images', 'info', 'key-round', 'keyboard', 'layers', 'link', 'list',
  'loader-circle', 'locate-fixed', 'lock', 'lock-open', 'map', 'map-pin', 'maximize', 'menu', 'minimize', 'minus',
  'monitor-smartphone', 'moon', 'mouse-pointer-2', 'music', 'paintbrush', 'panel-left', 'panel-right', 'pause',
  'pencil', 'play', 'plus', 'qr-code', 'quote', 'redo-2', 'refresh-cw', 'ruler', 'save', 'scan-eye', 'scroll-text',
  'search', 'send', 'settings', 'share-2', 'shield', 'skip-back', 'skip-forward', 'skull', 'smartphone', 'sparkles',
  'square', 'square-dashed', 'star', 'sun', 'sword', 'swords', 'tent', 'timer', 'triangle', 'triangle-alert', 'trash',
  'undo-2', 'upload', 'bold', 'italic', 'underline', 'strikethrough', 'list', 'list-ordered', 'list-checks', 'table', 'highlighter',
  'printer', 'pen-line', 'notebook-pen', 'file-plus', 'remove-formatting', 'user', 'users', 'volume-2', 'volume-x', 'wand-sparkles', 'wifi', 'wifi-off', 'x', 'zap',
];

// Drawn by hand to match Lucide's 24px, 2px-stroke, round-cap style.
const CUSTOM = {
  // The brand mark and the d20 every table knows.
  d20: [
    ['path', { d: 'M12 2.5 20.5 7.25v9.5L12 21.5l-8.5-4.75v-9.5Z' }],
    ['path', { d: 'M12 8 16.5 15.5h-9Z' }],
    ['path', { d: 'M12 2.5V8M20.5 7.25 16.5 15.5M3.5 7.25 7.5 15.5M3.5 16.75l4-1.25M20.5 16.75l-4-1.25M12 21.5l-4.5-6M12 21.5l4.5-6' }],
  ],
  // A spell cone: apex at the bottom, fanning upward.
  cone: [
    ['path', { d: 'M12 21 3.5 7.5a12 12 0 0 1 17 0Z' }],
    ['path', { d: 'M12 21V9.5', opacity: '0.55' }],
  ],
};

const icons = {};
for (const name of NAMES) {
  const module = await import(pathToFileURL(join(source, `${name}.mjs`)).href);
  icons[name] = module.default.node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
}
Object.assign(icons, CUSTOM);

const body = Object.entries(icons).sort(([a], [b]) => a.localeCompare(b))
  .map(([name, nodes]) => `  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`).join('\n');
await writeFile(join(root, 'src', 'icons.js'),
  `// Generated by scripts/build-icons.mjs from Lucide (ISC licence) plus hand-drawn d20 and cone.\n` +
  `// Each icon is a list of [tag, attributes] on a 24×24 grid, drawn with a 2px round stroke.\n` +
  `export const ICONS = {\n${body}\n};\n`);
console.log(`Wrote ${Object.keys(icons).length} icons`);
